      SUBROUTINE SHIELD (R,S,D50,SHR)
      VIS=0.00001217
      RSTR=5.67*SQRT(R*S)*D50/(305.*VIS)
      ZD=1./S
      IF(RSTR.LE.30) SHC=10.0**(-1.208-0.194*ALOG10(RSTR))
      IF(RSTR.GT.30.0.AND.RSTR.LE.200.0) SHC=10.0**(-1.49+0.35*
     1  (ALOG10(RSTR)-1.48))
      IF(RSTR.GT.200.0.AND.RSTR.LE.25000.) SHC=0.062
      IF(RSTR.GT.25000.0.AND.RSTR.LE.90000.) SHC=10.0**(-1.21+1.09*
     1  (ALOG10(RSTR)-4.4))
      IF(RSTR.GT.90000.) SHC=0.25
      FKS=ZD/SQRT(1.0+ZD*ZD)*(1.0-1.54/ZD)
      SHR=FKS*SHC
      RETURN
      END
